package com.surveyflow.common.enums;

public enum SurveyStatus {
    /** 草稿暫存：僅發布者可見與編輯，尚未公開至大廳 */
    DRAFT,

    /** 正式發布中：公開於問卷大廳，允許受訪者填答（須在有效日期範圍內） */
    PUBLISHED,

    /** 已截止關閉：停止收件，不再接受新填答，僅保留統計分析查閱功能 */
    CLOSED
}
